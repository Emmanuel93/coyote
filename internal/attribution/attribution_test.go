func TestComentariosDeGitConAtribucion(t *testing.T) {
	msg := "fix: algo\n\n# 🤖 Generated with [Claude Code](https://claude.com/claude-code)\n# On branch main\n"
	out, found := cfg(t).ScrubLines(msg, true)
	if len(found) != 1 || strings.Contains(out, "Claude Code") {
		t.Fatalf("la línea comentada con atribución debe salir: %+v\n%s", found, out)
	}
	if !strings.Contains(out, "# On branch main") {
		t.Fatalf("los comentarios normales de git se conservan:\n%s", out)
	}
}
