func cfg(t *testing.T) *Config {
	t.Helper()
	c, err := Default()
	if err != nil {
		t.Fatal(err)
	}
	return c
}

func TestScrubCommitMessage(t *testing.T) {
	msg := "feat(pagos): reintento con idempotencia\n\nAgrega backoff exponencial.\n\n" +
		"Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>\n" +
		"Claude-Session: https://claude.ai/code/session_123\n" +
		"Co-authored-by: Ana Pérez <ana@example.com>\n" +
		"# Please enter the commit message for your changes.\n"
	out, found := cfg(t).ScrubLines(msg, true)
	if len(found) != 2 {
		t.Fatalf("se esperaban 2 hallazgos, hay %d: %+v", len(found), found)
	}
	for _, bad := range []string{"noreply@anthropic.com", "Claude-Session"} {
		if strings.Contains(out, bad) {
			t.Fatalf("quedó %q en:\n%s", bad, out)
		}
	}
	for _, good := range []string{"feat(pagos): reintento con idempotencia", "Agrega backoff", "Ana Pérez", "# Please enter"} {
		if !strings.Contains(out, good) {
			t.Fatalf("se perdió %q en:\n%s", good, out)
		}
	}
}

